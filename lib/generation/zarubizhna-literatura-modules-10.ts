/**
 * Зарубіжна література, 10 клас, рівень стандарту.
 * Розподіл годин по розділах — з офіційної програми (наказ МОН №698
 * від 03.08.2022): 34(35) год усього, 30 год текстуального вивчення,
 * 2 год позакласного читання, 2(3) год резерву; розвиток мовлення — у
 * межах годин на текстуальне вивчення.
 *
 * Сама програма розподіляє години лише по розділах, а не по окремих
 * творах усередині розділу ("Учитель самостійно розподіляє години на
 * вивчення художніх творів" — прямий текст пояснювальної записки).
 * Розподіл годин між конкретними творами тут — розумне наближення
 * (як у типових готових КТП), яке за потреби легко змінити вручну.
 * Твори, зазначені в програмі як "за вибором учителя", звужено до
 * одного-двох найпоширеніших у практиці варіантів.
 */

